const turbowasm_simd_descriptor *
turbowasm_simd_descriptor_find(uint32_t opcode) {
    size_t index;

    for (index = 0u;
         index < sizeof(descriptors) / sizeof(descriptors[0]);
         ++index) {
        if (descriptors[index].opcode == opcode)
            return &descriptors[index];
    }
    return NULL;
}
