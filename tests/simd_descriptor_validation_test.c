static void test_unknown_simd_opcode_fails_closed(void) {
    static const uint8_t bytes[] = {
        WASM_HEADER,
        0x01, 0x04, 0x01, 0x60, 0x00, 0x00,
        FUNCTION_TYPE0,
        0x0a, 0x06, 0x01, 0x04,
        0x00, 0xfd, 0x80, 0x02, 0x0b
    };
    assert(load(bytes, sizeof(bytes)) == TURBOWASM_UNSUPPORTED);
}

