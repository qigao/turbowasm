#include <turbowasm/turbowasm.h>

#ifdef NDEBUG
#undef NDEBUG
#endif
#include <assert.h>
#include <stddef.h>
#include <stdint.h>

#define WASM_HEADER \
    0x00, 0x61, 0x73, 0x6d, \
    0x01, 0x00, 0x00, 0x00

#define FUNCTION_TYPE0 \
    0x03, 0x02, 0x01, 0x00

static turbowasm_status load(const uint8_t *bytes, size_t size) {
    turbowasm_module module = {0};
    turbowasm_status status =
        turbowasm_module_load_borrowed(&module, bytes, size);
    if (status == TURBOWASM_OK)
        turbowasm_module_destroy(&module);
    return status;
}

static void test_i32x4_splat(void) {
    static const uint8_t bytes[] = {
        WASM_HEADER,
        0x01, 0x06, 0x01, 0x60, 0x01, 0x7f, 0x01, 0x7b,
        FUNCTION_TYPE0,
        0x0a, 0x08, 0x01, 0x06,
        0x00, 0x20, 0x00, 0xfd, 0x11, 0x0b
    };
    assert(load(bytes, sizeof(bytes)) == TURBOWASM_OK);
}

static void test_splat_rejects_wrong_scalar_type(void) {
    static const uint8_t bytes[] = {
        WASM_HEADER,
        0x01, 0x06, 0x01, 0x60, 0x01, 0x7d, 0x01, 0x7b,
        FUNCTION_TYPE0,
        0x0a, 0x08, 0x01, 0x06,
        0x00, 0x20, 0x00, 0xfd, 0x0f, 0x0b
    };
    assert(load(bytes, sizeof(bytes)) == TURBOWASM_MALFORMED_MODULE);
}

static void test_extract_lane_bounds(void) {
    static const uint8_t valid[] = {
        WASM_HEADER,
        0x01, 0x06, 0x01, 0x60, 0x01, 0x7b, 0x01, 0x7f,
        FUNCTION_TYPE0,
        0x0a, 0x09, 0x01, 0x07,
        0x00, 0x20, 0x00, 0xfd, 0x15, 0x0f, 0x0b
    };
    static const uint8_t invalid[] = {
        WASM_HEADER,
        0x01, 0x06, 0x01, 0x60, 0x01, 0x7b, 0x01, 0x7f,
        FUNCTION_TYPE0,
        0x0a, 0x09, 0x01, 0x07,
        0x00, 0x20, 0x00, 0xfd, 0x15, 0x10, 0x0b
    };

    assert(load(valid, sizeof(valid)) == TURBOWASM_OK);
    assert(load(invalid, sizeof(invalid)) ==
           TURBOWASM_MALFORMED_MODULE);
}

static void test_replace_lane(void) {
    static const uint8_t bytes[] = {
        WASM_HEADER,
        0x01, 0x07,
        0x01, 0x60, 0x02, 0x7b, 0x7e, 0x01, 0x7b,
        FUNCTION_TYPE0,
        0x0a, 0x0b, 0x01, 0x09,
        0x00,
        0x20, 0x00,
        0x20, 0x01,
        0xfd, 0x1e, 0x01,
        0x0b
    };
    assert(load(bytes, sizeof(bytes)) == TURBOWASM_OK);
}

static void test_shuffle_bounds(void) {
    static const uint8_t valid[] = {
        WASM_HEADER,
        0x01, 0x07,
        0x01, 0x60, 0x02, 0x7b, 0x7b, 0x01, 0x7b,
        FUNCTION_TYPE0,
        0x0a, 0x1a, 0x01, 0x18,
        0x00,
        0x20, 0x00,
        0x20, 0x01,
        0xfd, 0x0d,
        0x00, 0x01, 0x02, 0x03,
        0x04, 0x05, 0x06, 0x07,
        0x18, 0x19, 0x1a, 0x1b,
        0x1c, 0x1d, 0x1e, 0x1f,
        0x0b
    };
    static const uint8_t invalid[] = {
        WASM_HEADER,
        0x01, 0x07,
        0x01, 0x60, 0x02, 0x7b, 0x7b, 0x01, 0x7b,
        FUNCTION_TYPE0,
        0x0a, 0x1a, 0x01, 0x18,
        0x00,
        0x20, 0x00,
        0x20, 0x01,
        0xfd, 0x0d,
        0x00, 0x01, 0x02, 0x03,
        0x04, 0x05, 0x06, 0x07,
        0x18, 0x19, 0x1a, 0x1b,
        0x1c, 0x1d, 0x1e, 0x20,
        0x0b
    };

    assert(load(valid, sizeof(valid)) == TURBOWASM_OK);
    assert(load(invalid, sizeof(invalid)) ==
           TURBOWASM_MALFORMED_MODULE);
}

