#include <turbowasm/turbowasm.h>

#ifdef NDEBUG
#undef NDEBUG
#endif
#include <assert.h>
#include <stddef.h>
#include <stdint.h>

#define WASM_HEADER \
    0x00, 0x61, 0x73, 0x6d, \
    0x01, 0x00, 0x00, 0x00

#define MEMORY_ONE \
    0x05, 0x03, 0x01, 0x00, 0x01

static turbowasm_status load(const uint8_t *bytes, size_t size) {
    turbowasm_module module = {0};
    turbowasm_status status =
        turbowasm_module_load_borrowed(&module, bytes, size);
    if (status == TURBOWASM_OK)
        turbowasm_module_destroy(&module);
    return status;
}

static void test_widening_load_and_alignment(void) {
    static const uint8_t valid[] = {
        WASM_HEADER,
        0x01, 0x06,
        0x01, 0x60, 0x01, 0x7f, 0x01, 0x7b,
        0x03, 0x02, 0x01, 0x00,
        MEMORY_ONE,
        0x0a, 0x0a, 0x01, 0x08,
        0x00,
        0x20, 0x00,
        0xfd, 0x01, 0x03, 0x00,
        0x0b
    };
    static const uint8_t over_aligned[] = {
        WASM_HEADER,
        0x01, 0x06,
        0x01, 0x60, 0x01, 0x7f, 0x01, 0x7b,
        0x03, 0x02, 0x01, 0x00,
        MEMORY_ONE,
        0x0a, 0x0a, 0x01, 0x08,
        0x00,
        0x20, 0x00,
        0xfd, 0x01, 0x04, 0x00,
        0x0b
    };

    assert(load(valid, sizeof(valid)) == TURBOWASM_OK);
    assert(load(over_aligned, sizeof(over_aligned)) ==
           TURBOWASM_MALFORMED_MODULE);
}

static void test_splat_and_zero_loads(void) {
    static const uint8_t splat[] = {
        WASM_HEADER,
        0x01, 0x06,
        0x01, 0x60, 0x01, 0x7f, 0x01, 0x7b,
        0x03, 0x02, 0x01, 0x00,
        MEMORY_ONE,
        0x0a, 0x0a, 0x01, 0x08,
        0x00,
        0x20, 0x00,
        0xfd, 0x07, 0x00, 0x00,
        0x0b
    };
    static const uint8_t zero[] = {
        WASM_HEADER,
        0x01, 0x06,
        0x01, 0x60, 0x01, 0x7f, 0x01, 0x7b,
        0x03, 0x02, 0x01, 0x00,
        MEMORY_ONE,
        0x0a, 0x0a, 0x01, 0x08,
        0x00,
        0x20, 0x00,
        0xfd, 0x5c, 0x02, 0x00,
        0x0b
    };

    assert(load(splat, sizeof(splat)) == TURBOWASM_OK);
    assert(load(zero, sizeof(zero)) == TURBOWASM_OK);
}

static void test_lane_load_bounds(void) {
    static const uint8_t valid[] = {
        WASM_HEADER,
        0x01, 0x07,
        0x01, 0x60, 0x02, 0x7f, 0x7b, 0x01, 0x7b,
        0x03, 0x02, 0x01, 0x00,
        MEMORY_ONE,
        0x0a, 0x0d, 0x01, 0x0b,
        0x00,
        0x20, 0x00,
        0x20, 0x01,
        0xfd, 0x54, 0x00, 0x00, 0x0f,
        0x0b
    };
    static const uint8_t invalid_lane[] = {
        WASM_HEADER,
        0x01, 0x07,
        0x01, 0x60, 0x02, 0x7f, 0x7b, 0x01, 0x7b,
        0x03, 0x02, 0x01, 0x00,
        MEMORY_ONE,
        0x0a, 0x0d, 0x01, 0x0b,
        0x00,
        0x20, 0x00,
        0x20, 0x01,
        0xfd, 0x54, 0x00, 0x00, 0x10,
        0x0b
    };

    assert(load(valid, sizeof(valid)) == TURBOWASM_OK);
    assert(load(invalid_lane, sizeof(invalid_lane)) ==
           TURBOWASM_MALFORMED_MODULE);
}

static void test_lane_store(void) {
    static const uint8_t bytes[] = {
        WASM_HEADER,
        0x01, 0x06,
        0x01, 0x60, 0x02, 0x7f, 0x7b, 0x00,
        0x03, 0x02, 0x01, 0x00,
        MEMORY_ONE,
        0x0a, 0x0d, 0x01, 0x0b,
        0x00,
        0x20, 0x00,
        0x20, 0x01,
        0xfd, 0x58, 0x00, 0x00, 0x0f,
        0x0b
    };
    assert(load(bytes, sizeof(bytes)) == TURBOWASM_OK);
}


static void test_demote_promote_descriptor_gap(void) {
    static const uint8_t bytes[] = {
        WASM_HEADER,
        0x01, 0x06,
        0x01, 0x60, 0x01, 0x7b, 0x01, 0x7b,
        0x03, 0x02, 0x01, 0x00,
        0x0a, 0x08, 0x01, 0x06,
        0x00,
        0x20, 0x00,
        0xfd, 0x5e,
        0x0b
    };
    assert(load(bytes, sizeof(bytes)) == TURBOWASM_OK);
}

static void test_simd_memory_requires_memory(void) {
    static const uint8_t bytes[] = {
        WASM_HEADER,
        0x01, 0x06,
        0x01, 0x60, 0x01, 0x7f, 0x01, 0x7b,
        0x03, 0x02, 0x01, 0x00,
        0x0a, 0x0a, 0x01, 0x08,
        0x00,
        0x20, 0x00,
        0xfd, 0x07, 0x00, 0x00,
        0x0b
    };
    assert(load(bytes, sizeof(bytes)) ==
           TURBOWASM_MALFORMED_MODULE);
}

int main(void) {
    test_widening_load_and_alignment();
    test_splat_and_zero_loads();
    test_lane_load_bounds();
    test_lane_store();
    test_demote_promote_descriptor_gap();
    test_simd_memory_requires_memory();
    return 0;
}
