static turbowasm_component_value u32_value(uint32_t value) {
    turbowasm_component_value out = {0};
    out.kind = TURBOWASM_COMPONENT_TYPE_U32;
    out.as.u32 = value;
    return out;
}

static uint32_t invoke_u32(
    turbowasm_component_exec *exec,
    const char *name,
    const turbowasm_component_value *arguments,
    size_t argument_count) {
    turbowasm_component_value result = {0};
    turbowasm_trap trap = TURBOWASM_TRAP_NONE;
    turbowasm_status status = turbowasm_component_exec_invoke_export(
        exec,
        (const uint8_t *)name,
        (uint32_t)strlen(name),
        arguments,
        argument_count,
        &result,
        &trap);

    assert(status == TURBOWASM_OK);
    assert(trap == TURBOWASM_TRAP_NONE);
    assert(result.kind == TURBOWASM_COMPONENT_TYPE_U32);

    {
        uint32_t value = result.as.u32;
        turbowasm_component_value_destroy(&result);
        return value;
    }
}

static void test_resource_builtins_roundtrip(void) {
    turbowasm_component_binary component = {0};
    turbowasm_component_exec exec = {0};
    turbowasm_component_value argument = u32_value(77u);

    assert(turbowasm_component_binary_load(
               &component,
               resource_roundtrip_component,
               sizeof(resource_roundtrip_component)) == TURBOWASM_OK);

    assert(component.resource_builtin_count == 3u);
    assert(component.core_function_count == 4u);
    assert(component.core_instance_count == 2u);
    assert(component.core_instances[0].kind ==
           TURBOWASM_COMPONENT_CORE_INSTANCE_INLINE);
    assert(component.core_instances[1].kind ==
           TURBOWASM_COMPONENT_CORE_INSTANCE_INSTANTIATE);

    assert(turbowasm_component_exec_init(
               &exec, &component) == TURBOWASM_OK);
    assert(exec.resource_table.live_count == 0u);

    assert(invoke_u32(
               &exec, "roundtrip", &argument, 1u) == 77u);
    assert(exec.resource_table.live_count == 0u);

    turbowasm_component_exec_destroy(&exec);
    turbowasm_component_binary_destroy(&component);
}

static void test_resource_destructor_invokes_core_function(void) {
    turbowasm_component_binary component = {0};
    turbowasm_component_exec exec = {0};
    turbowasm_component_value argument = u32_value(123u);

    assert(turbowasm_component_binary_load(
               &component,
               resource_destructor_component,
               sizeof(resource_destructor_component)) == TURBOWASM_OK);

    assert(component.resource_builtin_count == 3u);
    assert(component.core_function_count == 6u);
    assert(component.type_graph.count == 3u);
    assert(component.type_graph.types[0].kind ==
           TURBOWASM_COMPONENT_TYPE_RESOURCE);
    assert(component.type_graph.types[0].as.resource.has_destructor);
    assert(component.type_graph.types[0].as.resource.destructor_index == 0u);

    assert(turbowasm_component_exec_init(
               &exec, &component) == TURBOWASM_OK);

    assert(invoke_u32(
               &exec, "roundtrip", &argument, 1u) == 123u);
    assert(exec.resource_table.live_count == 0u);
    assert(invoke_u32(
               &exec, "drops", NULL, 0u) == 1u);

    turbowasm_component_exec_destroy(&exec);
    turbowasm_component_binary_destroy(&component);
}

int main(void) {
    test_resource_builtins_roundtrip();
    test_resource_destructor_invokes_core_function();
    return 0;
}
