static void test_preopens_component_resource_roundtrip(void) {
    fake_fs fake = {0};
    turbowasm_wasi_fs filesystem = {0};
    turbowasm_wasi_fs_config fs_config = {0};
    turbowasm_wasi_fs_descriptor preopen = {0};
    turbowasm_wasi02_filesystem bridge = {0};
    turbowasm_component_binary binary = {0};
    turbowasm_component_exec exec = {0};
    turbowasm_component_value result = {0};
    turbowasm_trap trap = TURBOWASM_TRAP_NONE;
    turbowasm_instance_impl *memory_instance;
    uint8_t list_pair[8] = {0};
    uint8_t tuple_prefix[12] = {0};
    uint8_t path_byte = 0u;

    fs_config.descriptor_capacity = 4u;
    fs_config.provider.context = &fake;
    fs_config.provider.close = fake_close;
    fs_config.provider.read = fake_read;
    fs_config.provider.write = fake_write;
    assert(turbowasm_wasi_fs_init(
               &filesystem, &fs_config) == TURBOWASM_OK);
    assert(turbowasm_wasi_fs_bind_descriptor(
               &filesystem,
               7u,
               (turbowasm_wasi_fs_file){UINT64_C(11), 1u},
               true,
               "/",
               &preopen) == TURBOWASM_OK);

    assert(turbowasm_wasi02_filesystem_init(
               &bridge, &filesystem, 8u) == TURBOWASM_OK);
    assert(turbowasm_component_binary_load(
               &binary,
               preopens_component,
               sizeof(preopens_component)) == TURBOWASM_OK);
    assert(binary.import_count == 2u);
    assert(binary.resource_builtin_count == 1u);
    assert(binary.canon_lower_count == 1u);

    assert(turbowasm_wasi02_filesystem_component_exec_init(
               &exec, &binary, &bridge) == TURBOWASM_OK);
    assert(bridge.descriptor_identity_bound);

    assert(turbowasm_component_exec_invoke_export(
               &exec,
               (const uint8_t *)"run", 3u,
               NULL, 0u,
               &result, &trap) == TURBOWASM_OK);
    assert(trap == TURBOWASM_TRAP_NONE);
    assert(result.kind == TURBOWASM_COMPONENT_TYPE_U32);
    assert(result.as.u32 == 1u);

    /* The guest's canon resource.drop consumed the logical WIT handle. */
    assert(bridge.resources.live_count == 0u);
    /* The host-owned backing preopen is still alive. */
    assert(fake.close_calls == 0u);

    memory_instance =
        (turbowasm_instance_impl *)exec.core_instances[0].impl;
    assert(memory_instance != NULL);
    assert(turbowasm_instance_memory_read_bytes(
               memory_instance, 0u, 0u, 0u,
               list_pair, sizeof(list_pair)) == TURBOWASM_OK);
    assert(list_pair[0] == 0x00u);
    assert(list_pair[1] == 0x01u);
    assert(list_pair[4] == 1u);

    assert(turbowasm_instance_memory_read_bytes(
               memory_instance, 0u, 256u, 0u,
               tuple_prefix, sizeof(tuple_prefix)) == TURBOWASM_OK);
    assert(tuple_prefix[0] != 0u ||
           tuple_prefix[1] != 0u ||
           tuple_prefix[2] != 0u ||
           tuple_prefix[3] != 0u);
    assert(tuple_prefix[4] == 0x00u);
    assert(tuple_prefix[5] == 0x02u);
    assert(tuple_prefix[8] == 1u);

    assert(turbowasm_instance_memory_read_bytes(
               memory_instance, 0u, 512u, 0u,
               &path_byte, 1u) == TURBOWASM_OK);
    assert(path_byte == (uint8_t)'/');

    turbowasm_component_value_destroy(&result);
    turbowasm_component_exec_destroy(&exec);
    turbowasm_component_binary_destroy(&binary);
    assert(turbowasm_wasi02_filesystem_destroy(
               &bridge) == TURBOWASM_OK);

    assert(turbowasm_wasi_fs_close_descriptor(
               &filesystem, preopen) == TURBOWASM_WASI_ERRNO_SUCCESS);
    assert(fake.close_calls == 1u);
    assert(turbowasm_wasi_fs_destroy(
               &filesystem) == TURBOWASM_OK);
}

int main(void) {
    test_preopens_component_resource_roundtrip();
    return 0;
}
